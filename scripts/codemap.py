"""Regenerate docs/CODEMAP.md: one line per source file, so agents open only what they need.

Run: python3 scripts/codemap.py   (no dependencies; safe to run any time)
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "CODEMAP.md"
MAX_LINES = 300  # files above this are flagged; split them before they grow further

SECTIONS = [
    ("Python pipeline", "src/mandarin_course", "*.py"),
    ("Python scripts", "scripts", "*.py"),
    ("Python tests", "tests", "*.py"),
    ("Supabase migrations", "supabase/migrations", "*.sql"),
    ("KMP shared (main)", "kmp/shared/src/commonMain", "*.kt"),
    ("KMP shared (tests)", "kmp/shared/src/commonTest", "*.kt"),
    ("Android app (main)", "kmp/android/src/main", "*.kt"),
    ("Android app (tests)", "kmp/android/src/test", "*.kt"),
]

KOTLIN_DECL = re.compile(
    r"^(?:@\w+(?:\([^)]*\))?\s+)*(?:(?:public|internal|private|abstract|open|sealed|data|enum|"
    r"annotation|inline|value|fun)\s+)*(class|object|interface|fun)\s+([A-Za-z_][\w.]*)",
    re.M,
)


def python_summary(path: Path) -> str:
    try:
        doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8")))
    except SyntaxError:
        doc = None
    return doc.strip().splitlines()[0] if doc else ""


def kotlin_summary(text: str) -> str:
    kdoc = re.search(r"/\*\*\s*\n?\s*\*?\s*(.+?)(?:\n|\*/)", text)
    names = [name for kind, name in KOTLIN_DECL.findall(text) if kind != "fun"][:4]
    if not names:
        names = [name for _, name in KOTLIN_DECL.findall(text)][:4]
    parts = []
    if names:
        parts.append(", ".join(names))
    if kdoc:
        parts.append(kdoc.group(1).strip().rstrip("*/ ").strip())
    return " — ".join(parts)


def sql_summary(text: str) -> str:
    for line in text.splitlines():
        if line.startswith("--"):
            return line.lstrip("- ").strip()
    return ""


def summary(path: Path) -> str:
    text = path.read_text(encoding="utf-8", errors="ignore")
    if path.suffix == ".py":
        return python_summary(path)
    if path.suffix == ".kt":
        return kotlin_summary(text)
    if path.suffix == ".sql":
        return sql_summary(text)
    return ""


def main() -> None:
    out = [
        "# Code map",
        "",
        "Generated by `python3 scripts/codemap.py` — do not edit by hand; rerun after adding, moving or splitting files.",
        f"Lines in brackets; ⚠ marks files over {MAX_LINES} lines (split before extending them).",
        "Lesson content and generated data (lessons/*.json, publish/, cache/, output/) are not listed.",
        "",
    ]
    for title, folder, pattern in SECTIONS:
        base = ROOT / folder
        files = sorted(p for p in base.rglob(pattern) if "build" not in p.parts and "__pycache__" not in p.parts)
        if not files:
            continue
        out += [f"## {title} (`{folder}/`)", ""]
        for path in files:
            lines = sum(1 for _ in path.open(encoding="utf-8", errors="ignore"))
            flag = " ⚠" if lines > MAX_LINES else ""
            rel = path.relative_to(base).as_posix()
            desc = summary(path)
            out.append(f"- `{rel}` [{lines}]{flag}" + (f" — {desc}" if desc else ""))
        out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(out)} lines)")


if __name__ == "__main__":
    main()
